#!/usr/bin/env python3
"""Generates the icon enum of an icon pack crate from its font's metadata.

    scripts/generate_icons.py lucide violet-lucide/bin/lucide/info.json violet-lucide/src/icons.rs
    scripts/generate_icons.py phosphor violet-phosphor/bin/style.css violet-phosphor/src/icons.rs

The output defines `<Pack>Icon` with a variant per icon, its glyph and kebab-case name, lookup by
name, and conversion into `violet_core::icon::Icon` using the pack's font family.
"""

import json
import re
import sys
from pathlib import Path

PACKS = {
    "lucide": {
        "enum": "LucideIcon",
        "family": "lucide",
        "fallback": "circle-help",
    },
    "phosphor": {
        "enum": "PhosphorIcon",
        "family": "Phosphor",
        "fallback": "question",
    },
}


def parse_lucide(source: str) -> list[tuple[str, int]]:
    data = json.loads(source)
    return [(name, int(info["encodedCode"].lstrip("\\"), 16)) for name, info in data.items()]


def parse_phosphor(source: str) -> list[tuple[str, int]]:
    pattern = re.compile(r'\.ph\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"')
    return [(name, int(code, 16)) for name, code in pattern.findall(source)]


def variant_name(name: str) -> str:
    variant = "".join(part[:1].upper() + part[1:] for part in name.split("-"))
    return f"N{variant}" if variant[:1].isdigit() else variant


def generate(pack: str, icons: list[tuple[str, int]]) -> str:
    config = PACKS[pack]
    enum = config["enum"]
    icons = sorted(icons)

    variants = [variant_name(name) for name, _ in icons]
    duplicates = {v for v in variants if variants.count(v) > 1}
    if duplicates:
        sys.exit(f"Variant names collide: {sorted(duplicates)}")

    names = [name for name, _ in icons]
    if config["fallback"] not in names:
        sys.exit(f"Fallback icon {config['fallback']!r} does not exist")
    fallback = variant_name(config["fallback"])

    out = [
        f"// @generated by scripts/generate_icons.py {pack}. Do not edit.",
        "",
        "use std::{fmt, str::FromStr};",
        "",
        "use violet_core::icon::{Icon, UnknownIcon};",
        "",
        f"/// Font family of the {pack} icon font",
        f'pub const FONT_FAMILY: &str = "{config["family"]}";',
        "",
        f"/// Every icon in the {pack} icon font",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]",
        f"pub enum {enum} {{",
    ]
    out += [f"    {variant}," for variant in variants]
    out += [
        "}",
        "",
        f"impl {enum} {{",
        "    /// All icons, ordered by name",
        "    pub const ALL: &[Self] = &[",
    ]
    out += [f"        Self::{variant}," for variant in variants]
    out += [
        "    ];",
        "",
        "    /// Icon shown when parsing an unknown name with [`Self::parse_or_fallback`]",
        f"    pub const FALLBACK: Self = Self::{fallback};",
        "",
        "    /// The glyph of this icon in the icon font",
        "    pub const fn glyph(self) -> &'static str {",
        "        match self {",
    ]
    out += [
        f'            Self::{variant} => "\\u{{{code:x}}}",'
        for variant, (_, code) in zip(variants, icons)
    ]
    out += [
        "        }",
        "    }",
        "",
        "    /// The icon's kebab-case name, as used by the upstream icon set",
        "    pub const fn name(self) -> &'static str {",
        "        match self {",
    ]
    out += [f'            Self::{variant} => "{name}",' for variant, (name, _) in zip(variants, icons)]
    out += [
        "        }",
        "    }",
        "",
        "    /// Looks up an icon by its kebab-case name",
        "    pub fn from_name(name: &str) -> Option<Self> {",
        "        match name {",
    ]
    out += [f'            "{name}" => Some(Self::{variant}),' for variant, (name, _) in zip(variants, icons)]
    out += [
        "            _ => None,",
        "        }",
        "    }",
        "",
        "    /// Looks up an icon by name, logging a warning and returning [`Self::FALLBACK`] if it",
        "    /// does not exist",
        "    pub fn parse_or_fallback(name: &str) -> Self {",
        "        Self::from_name(name).unwrap_or_else(|| {",
        f'            tracing::warn!("Unknown {pack} icon {{name:?}}");',
        "            Self::FALLBACK",
        "        })",
        "    }",
        "}",
        "",
        f"impl From<{enum}> for Icon {{",
        f"    fn from(icon: {enum}) -> Self {{",
        "        Icon::new(FONT_FAMILY, icon.glyph())",
        "    }",
        "}",
        "",
        f"impl FromStr for {enum} {{",
        "    type Err = UnknownIcon;",
        "",
        "    fn from_str(name: &str) -> Result<Self, Self::Err> {",
        "        Self::from_name(name).ok_or_else(|| UnknownIcon::new(name))",
        "    }",
        "}",
        "",
        f"impl fmt::Display for {enum} {{",
        "    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {",
        "        f.write_str(self.name())",
        "    }",
        "}",
        "",
    ]
    return "\n".join(out)


def main() -> None:
    if len(sys.argv) != 4 or sys.argv[1] not in PACKS:
        sys.exit(f"usage: {sys.argv[0]} <{'|'.join(PACKS)}> <source> <output.rs>")

    pack, source, output = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
    parse = {"lucide": parse_lucide, "phosphor": parse_phosphor}[pack]
    icons = parse(source.read_text())
    output.write_text(generate(pack, icons))
    print(f"Wrote {len(icons)} {pack} icons to {output}")


if __name__ == "__main__":
    main()
